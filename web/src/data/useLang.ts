type LangState = {
    visible: boolean;
    placing: boolean;
    fade: boolean;
    fadeOpacity: number;
    /** Filling the screen rather than sitting in a window. */
    expanded: boolean;
    lang: Record<string, string>;
};

const EXPANDED_KEY = 'gg_settings_expanded';

// Somewhere to put a preference that is nobody's business but this player's.
// Any of these can throw -- a private window, site data switched off -- and a
// window that opens at the wrong size is not worth a broken page.
function readExpanded(): boolean {
    try {
        return window.localStorage.getItem(EXPANDED_KEY) === '1';
    } catch {
        return false;
    }
}

export function toggleExpanded() {
    const next = !useLang.getState().expanded;

    useLang.setState({ expanded: next });

    try {
        window.localStorage.setItem(EXPANDED_KEY, next ? '1' : '0');
    } catch {
        // Not being able to remember it is not a reason to refuse to do it.
    }
}

export const useLang = create<LangState>(() => ({
    visible: false,
    placing: false,
    fade: true,
    fadeOpacity: 90,
    expanded: readExpanded(),
    lang: defaultLang,
}));

export function applyAppearance(data: { UI_THEME?: string; UI_FADE?: boolean; UI_FADE_TO?: number }) {
    applyTheme(data.UI_THEME);

    useLang.setState((state) => ({
        fade: typeof data.UI_FADE === 'boolean' ? data.UI_FADE : state.fade,
        fadeOpacity: typeof data.UI_FADE_TO === 'number' ? data.UI_FADE_TO : state.fadeOpacity,
    }));
}

export function t(key: string): string {
    return useLang.getState().lang[key] ?? defaultLang[key] ?? key;
}

export function applyTheme(color?: string) {
    if (!color) return;

    const parsed = parseColor(color);

    if (parsed.spaceSeparated) {
        document.documentElement.style.setProperty('--primary', parsed.spaceSeparated);
        document.documentElement.style.setProperty('--primary-rgb', parsed.commaSeparated);
    }
}

export function showEditor(uiLang?: Record<string, string>) {
    useLang.setState({
        visible: true,
        lang: { ...defaultLang, ...(uiLang ?? {}) },
    });
}

export function hideEditor() {
    useLang.setState({ visible: false });
}
